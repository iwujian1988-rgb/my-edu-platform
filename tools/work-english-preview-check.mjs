import {chromium,expect} from '@playwright/test';
import fs from 'node:fs/promises';
const id=process.argv[2]||'002';
const port=Number(process.env.WORK_ENGLISH_PREVIEW_PORT||3004);
const lesson=JSON.parse(await fs.readFile('src/content/work-english/'+id+'/lesson.json','utf8'));
const url='http://127.0.0.1:'+port+'/work-english/lessons/'+id;
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.goto(url);
await expect(page.locator('#sourceSheet')).toBeVisible();
await expect(page.locator('#lessonIllustration')).toBeVisible();
await page.screenshot({path:'linshi/work-english-acceptance/screenshots/lesson-'+id+'-desktop.png'});
await page.locator('#annotateReadBtn').click();
await page.locator('[data-note]').first().click();
await expect(page.locator('#docNoteDetail')).toBeVisible();
await page.locator('#translationBtn').click();
await expect(page.locator('#translation')).toBeVisible();
await page.locator('#hideTranscript').check();
await expect(page.locator('.sentence-transcript').first()).toBeHidden();
await page.locator('#hideTranscript').uncheck();
await expect(page.locator('.sentence-transcript').first()).toBeVisible();
await page.locator('.save-word').first().click();
await expect(page.locator('#wordCount')).toContainText('1 个');
await page.locator('#vocabRecall').check();
if(await page.locator('#wordCards .task-phrase .word-meaning').first().isVisible())throw new Error('Vocabulary recall should hide task phrase meanings');
await page.locator('#vocabRecall').uncheck();
for(const item of lesson.cloze)await page.locator('#'+item.id).fill(item.answer);
await page.locator('#checkCloze').click();
await expect(page.locator('#c1Feedback')).toContainText('答对了');
await expect(page.locator('#exerciseSummary')).toContainText('3 / 6');
const dictation=lesson.dictation[0];
const partial=dictation.text.split(/\s+/).slice(0,-1).join(' ');
await page.locator('#'+dictation.id+'Input').fill(partial);
await page.locator('[data-check-dictation="'+dictation.id+'"]').click();
await expect(page.locator('#'+dictation.id+'Feedback .missing')).toHaveCount(1);
const wrongChoice=lesson.choice.correct===0?1:0;
await page.locator('input[name="quiz"][value="'+wrongChoice+'"]').check();
await page.locator('#checkQuiz').click();
await expect(page.locator('#exerciseSummary')).toContainText('5 / 6');
await expect(page.locator('#reviewQueue a[href="#quizFeedback"]')).toBeVisible();
await page.locator('#compareWriting').click();
await expect(page.locator('#writingComparison')).toBeHidden();
await expect(page.locator('#outputCheck')).toContainText('先完成');
await page.locator('#warmupInput').fill('My first attempt.');
await page.locator('#practiceInput').fill('My revised work expression.');
await page.locator('#compareWriting').click();
await expect(page.locator('#beforeWriting')).toHaveText('My first attempt.');
await expect(page.locator('#afterWriting')).toHaveText('My revised work expression.');
await page.locator('#reviewStart').click();
await expect(page.locator('#reviewCard')).toBeVisible();
await page.locator('#reviewReveal').click();
await expect(page.locator('#reviewRating')).toBeVisible();
await page.locator('[data-play="original"]').first().click();
await expect.poll(()=>page.locator('#lessonAudio').evaluate(a=>a.currentTime),{timeout:15000}).toBeGreaterThan(0);
await expect(page.locator('#audioStatus')).toContainText('正在播放');
await expect(page.locator('#miniAudio')).toBeVisible();
await page.locator('#miniPause').click();
await expect.poll(()=>page.locator('#lessonAudio').evaluate(a=>a.paused)).toBe(true);
await page.locator('#miniPause').click();
await expect.poll(()=>page.locator('#lessonAudio').evaluate(a=>a.paused)).toBe(false);
await page.locator('#miniStop').click();
await expect(page.locator('#miniAudio')).toBeHidden();
await page.locator('#lessonAudio').evaluate(a=>a.pause());
await page.setViewportSize({width:390,height:844});
await page.goto(url);
await page.screenshot({path:'linshi/work-english-acceptance/screenshots/lesson-'+id+'-mobile.png'});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Mobile horizontal overflow');
if(errors.length)throw new Error('Page errors: '+errors.join('; '));
console.log(JSON.stringify({id,status:'PASS',checks:['source','illustration','notes','translation','words','cloze','audio','mobile'],errors}));
await browser.close();
